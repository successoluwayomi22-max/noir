ALTER TABLE products
    ADD COLUMN gender VARCHAR(40) NULL AFTER brand,
    ADD COLUMN material VARCHAR(120) NULL AFTER gender,
    ADD COLUMN season VARCHAR(80) NULL AFTER material,
    ADD COLUMN best_seller BOOLEAN NOT NULL DEFAULT FALSE AFTER featured,
    ADD COLUMN view_count INT UNSIGNED NOT NULL DEFAULT 0 AFTER best_seller;

CREATE TABLE collections (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    slug VARCHAR(180) NOT NULL UNIQUE,
    description TEXT NULL,
    image VARCHAR(255) NULL,
    is_featured BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE product_collections (
    product_id BIGINT UNSIGNED NOT NULL,
    collection_id BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(product_id, collection_id),
    FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE,
    FOREIGN KEY(collection_id) REFERENCES collections(id) ON DELETE CASCADE,
    INDEX(collection_id)
) ENGINE=InnoDB;
